"""Export Blue's winning strategies for the 12 scored puzzles (seed "1") as Lean data.

Untrusted: the strategies come from thinice/search.py. Lean re-checks every one of them against
its own copy of the rules (lean/ThinIce/Rules.lean), so a bad hint can only make a proof fail,
never make a false theorem build.

Writes lean/ThinIce/Puzzles.lean (the 12 start positions) and lean/ThinIce/Hints/Pxx.lean
(one hint table per puzzle: for each Blue-to-move node with n >= 2 that the strategy reaches,
the move to play). Nodes where Blue wins at once need no hint; Lean finds that move itself.

Usage: python tools/lean_export.py [--only P12] [--min-hint 2]
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.setrecursionlimit(10000)

from thinice.board import completes_line, moves, squares  # noqa: E402
from thinice.search import Searcher  # noqa: E402
from thinice.session import load_pack, pick  # noqa: E402

PACKS = ROOT / "task" / "environment" / "game-server" / "packs"
LEAN = ROOT / "lean" / "ThinIce"


def puzzles():
    manifest = json.loads((PACKS / "manifest.json").read_text())
    return pick(load_pack(PACKS / "scored.jsonl"), "1", manifest["tiers"], manifest["per_tier"])


def strategy(blue: int, red: int, n: int, min_hint: int):
    """Walk Blue's strategy over every Red reply; return {(blue, red, n): (from, to)} hints."""
    s = Searcher(None)
    if s.attack(blue, red, n) is None:
        raise SystemExit(f"search found no win within {n}")
    hints: dict = {}
    seen: set = set()

    def walk(b: int, r: int, k: int) -> None:
        if (b, r, k) in seen:
            return
        seen.add((b, r, k))
        mv = s.attack(b, r, k)
        assert mv is not None
        f, t = mv
        nb = b ^ (1 << f) ^ (1 << t)
        if completes_line(nb, t):
            return
        if k >= min_hint:
            hints[(b, r, k)] = mv
        for rf, rt in moves(r, nb | r):
            nr = r ^ (1 << rf) ^ (1 << rt)
            assert not completes_line(nr, rt)
            walk(nb, nr, k - 1)

    walk(blue, red, n)
    return hints


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default=None)
    ap.add_argument("--min-hint", type=int, default=2)
    args = ap.parse_args()
    chosen = puzzles()
    (LEAN / "Hints").mkdir(parents=True, exist_ok=True)
    rows = []
    for i, p in enumerate(chosen, 1):
        name = f"P{i:02d}"
        rows.append((name, p))
        nb = len(moves(p.blue, p.blue | p.red))
        print(f"{name} blue={squares(p.blue)} red={squares(p.red)} depth={p.depth} N={p.need} blue_moves={nb}", flush=True)
    with open(LEAN.parent / "ThinIce" / "Puzzles.lean", "w", encoding="utf-8", newline="\n") as fh:
        fh.write("-- Generated by tools/lean_export.py: the 12 scored puzzles picked with seed \"1\".\n")
        fh.write("import ThinIce.Rules\n\nnamespace ThinIce\n\n")
        for name, p in rows:
            fh.write(f"/-- {name}: Blue to move, forced win in {p.need} (pack index {p.index}). -/\n")
            fh.write(f"def {name} : Pos := ofSquares {squares(p.blue)} {squares(p.red)}\n")
            fh.write(f"def {name}.need : Nat := {p.need}\n")
            py = moves(p.blue, p.blue | p.red)
            fh.write(f"def {name}.blueMoves : Nat := {len(py)}\n")
            fh.write("/-- board.moves for Blue at the start, as Python lists it. -/\n")
            fh.write(f"def {name}.pyMoves : List (Nat × Nat) := {[tuple(m) for m in py]}\n\n")
        fh.write("end ThinIce\n")
    for name, p in rows:
        if args.only == "none" or (args.only and name != args.only):
            continue
        t0 = time.monotonic()
        hints = strategy(p.blue, p.red, p.need, args.min_hint)
        body = ",\n  ".join(f"(({b}, {r}, {k}), ({f}, {t}))" for (b, r, k), (f, t) in sorted(hints.items()))
        with open(LEAN / "Hints" / f"{name}.lean", "w", encoding="utf-8", newline="\n") as fh:
            fh.write(f"-- Generated by tools/lean_export.py. Untrusted hints for {name}: ((blue, red, n), (from, to)).\n")
            fh.write("namespace ThinIce.Hints\n\n")
            fh.write(f"def {name} : List ((Nat × Nat × Nat) × (Nat × Nat)) := [\n  {body}]\n\nend ThinIce.Hints\n")
        print(f"{name}: {len(hints)} hints, {time.monotonic() - t0:.1f}s", flush=True)


if __name__ == "__main__":
    main()
